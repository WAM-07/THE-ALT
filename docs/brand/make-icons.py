"""Copies the logo pack (docs/brand/logo-pack) into the apps: launcher icons, splash logos, favicons.

Run from the repository root after changing the pack:  python docs/brand/make-icons.py
Needs Pillow (pip install pillow). Only writes files; the code that shows them is in each app.
"""
import pathlib
import shutil

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[2]
PACK = ROOT / 'docs' / 'brand' / 'logo-pack'
INK = (0x0E, 0x15, 0x25, 255)

# Android density buckets: legacy launcher icon (48 dp) and adaptive layer (108 dp) in pixels.
DENSITIES = {'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4}


def resized(path, px):
    return Image.open(path).convert('RGBA').resize((px, px), Image.LANCZOS)


def centred(logo_path, canvas_px, logo_px, bg=(0, 0, 0, 0)):
    canvas = Image.new('RGBA', (canvas_px, canvas_px), bg)
    logo = resized(logo_path, logo_px)
    canvas.alpha_composite(logo, ((canvas_px - logo_px) // 2, (canvas_px - logo_px) // 2))
    return canvas


def android(app, kind, icon_names):
    res = ROOT / 'apps' / app / 'android' / 'app' / 'src' / 'main' / 'res'
    rounded = PACK / 'app-icons' / 'png' / f'{kind}-icon-rounded-1024.png'
    logo_on_dark = PACK / 'png' / f'{kind}-dark-1024.png'
    for bucket, scale in DENSITIES.items():
        folder = res / f'mipmap-{bucket}'
        folder.mkdir(exist_ok=True)
        for name in icon_names:
            resized(rounded, round(48 * scale)).save(folder / f'{name}.png')
        # Adaptive foreground: the logo where the pack's tile puts it (70% of the 72 dp visible area).
        layer = round(108 * scale)
        centred(logo_on_dark, layer, round(layer * 0.7 * 72 / 108)).save(folder / f'{icon_names[0]}_foreground.png')
    anydpi = res / 'mipmap-anydpi-v26'
    anydpi.mkdir(exist_ok=True)
    xml = ('<?xml version="1.0" encoding="utf-8"?>\n'
           '<!-- Generated by docs/brand/make-icons.py from the logo pack. -->\n'
           '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
           '    <background android:drawable="@color/brand_ink" />\n'
           f'    <foreground android:drawable="@mipmap/{icon_names[0]}_foreground" />\n'
           f'    <monochrome android:drawable="@mipmap/{icon_names[0]}_foreground" />\n'
           '</adaptive-icon>\n')
    for name in icon_names:
        (anydpi / f'{name}.xml').write_text(xml, encoding='utf-8')
    (res / 'values' / 'brand_colors.xml').write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<!-- The logo pack\'s ink (docs/brand/logo-pack). -->\n'
        '<resources>\n    <color name="brand_ink">#0E1525</color>\n</resources>\n', encoding='utf-8')
    # The logo on the native launch screen, before Flutter draws its first frame.
    nodpi = res / 'drawable-nodpi'
    nodpi.mkdir(exist_ok=True)
    resized(logo_on_dark, 288).save(nodpi / 'launch_logo.png')


def flutter_web(app, kind):
    web = ROOT / 'apps' / app / 'web'
    rounded = PACK / 'app-icons' / 'png' / f'{kind}-icon-rounded-1024.png'
    square = PACK / 'app-icons' / 'png' / f'{kind}-icon-square-1024.png'
    resized(rounded, 32).save(web / 'favicon.png')
    for px in (192, 512):
        resized(rounded, px).save(web / 'icons' / f'Icon-{px}.png')
        resized(square, px).save(web / 'icons' / f'Icon-maskable-{px}.png')


def next_app(app, kind, folder):
    """Next.js picks up app/icon.svg (browsers) and app/apple-icon.png (home screens) by name."""
    out = ROOT / 'apps' / app / folder
    shutil.copy(PACK / 'app-icons' / f'{kind}-icon-rounded.svg', out / 'icon.svg')
    resized(PACK / 'app-icons' / 'png' / f'{kind}-icon-square-1024.png', 180).save(out / 'apple-icon.png')
    ico = resized(PACK / 'app-icons' / 'png' / f'{kind}-icon-rounded-1024.png', 256)
    ico.save(out / 'favicon.ico', sizes=[(16, 16), (32, 32), (48, 48)])


if __name__ == '__main__':
    android('alter', 'alter', ['ic_launcher'])
    android('altera', 'altera', ['launcher_icon', 'ic_launcher'])
    flutter_web('alter', 'alter')
    flutter_web('altera', 'altera')
    next_app('altar-web', 'altar', 'src/app')
    next_app('command-centre', 'alt', 'src/app')
    print('icons written')
