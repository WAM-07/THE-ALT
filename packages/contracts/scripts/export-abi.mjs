// Copies the compiled ABIs into abi/ so services can use them without compiling Solidity.
// Run after `hardhat build`: npm run build -w @alt/contracts
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const contracts = { AITRegistry: 'aitRegistryAbi', ALTMarketplace: 'altMarketplaceAbi' };
mkdirSync(path.join(root, 'abi'), { recursive: true });
let js = '// Generated by scripts/export-abi.mjs. Do not edit.\n';
let dts = '// Generated by scripts/export-abi.mjs. Do not edit.\n';
for (const [name, exportName] of Object.entries(contracts)) {
  const artifact = JSON.parse(readFileSync(path.join(root, 'artifacts', 'contracts', `${name}.sol`, `${name}.json`), 'utf8'));
  const abi = JSON.stringify(artifact.abi, null, 2);
  js += `\nexport const ${exportName} = ${abi};\n`;
  // Literal types let viem infer function names, arguments and events.
  dts += `\nexport declare const ${exportName}: ${abi.replace(/^(\s*)\[/gm, '$1readonly [')};\n`;
}
writeFileSync(path.join(root, 'abi', 'index.js'), js);
writeFileSync(path.join(root, 'abi', 'index.d.ts'), dts);
console.log('exported ABIs for', Object.keys(contracts).join(', '));
